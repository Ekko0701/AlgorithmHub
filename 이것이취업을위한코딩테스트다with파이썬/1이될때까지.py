# 문제: 1이 될 때까지
# 어떤 수 N이 1이 될 때까지 다음 두 과정 중 하나를 반복적으로 선택하여 수행한다.
# 1. N에서 1을 뺀다.
# 2. N이 K로 나누어떨어질 때만 N을 K로 나눈다.
# 이때 N이 1이 될 때까지 수행해야 하는 최소 횟수를 구하는 문제.
# 입력:
# - 첫째 줄에 N(자연수), K(자연수)
# 출력:
# - N이 1이 될 때까지 수행하는 최소 횟수
# 예시 입력:
# 25 5
# 예시 출력:
# 2

N, K = map(int, input().split())
count = 0

while N != 1:
    if N % K == 0:
        N //= K
    else:
        N -= 1
    count += 1

print(count)
